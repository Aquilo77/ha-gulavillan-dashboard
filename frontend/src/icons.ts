export function domainIcon(entityId: string): string {
  return DOMAIN_ICONS[entityId.split(".")[0] ?? ""] ?? "mdi:circle-outline";
}

export function icon(name: string | undefined): TemplateResult | typeof nothing {
  const iconName = name && name.startsWith("mdi:") ? name : "";
  if (!iconName) return nothing;
  if (typeof customElements !== "undefined" && customElements.get("ha-icon")) {
    return html`<ha-icon icon=${iconName}></ha-icon>`;
  }
  const path = PATHS[iconName];
  if (!path) {
    return html`<svg class="ico" viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="4" fill="currentColor"></circle></svg>`;
  }
  return html`<svg class="ico" viewBox="0 0 24 24" aria-hidden="true"><path d=${path} fill="currentColor"></path></svg>`;
}
